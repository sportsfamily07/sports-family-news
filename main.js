const breakingText =
  document.querySelector(".breaking-content p");

let breakingIndex = 0;

function updateBreakingNews() {

  if (!breakingText || newsData.length === 0) {
    return;
  }

  const currentNews =
    newsData[breakingIndex];

  // News title
  breakingText.textContent =
    currentNews.title;

  // সেই News-এর ID সেট করবে
  breakingText.dataset.id =
    currentNews.id;

  breakingIndex++;

  if (breakingIndex >= newsData.length) {
    breakingIndex = 0;
  }

}


