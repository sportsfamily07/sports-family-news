function applyApiFilters() {

  const selectedUser =
    apiUserFilter.value;

  const searchText =
    apiSearchInput.value.toLowerCase().trim();

  const filteredPosts = apiPosts.filter(function(post) {

    const categories = [
      "football",
      "cricket",
      "nba",
      "boxing",
      "ufc"
    ];

    const category =
      categories[(post.id - 1) % categories.length];

    const matchesUser =
      selectedUser === "all" ||
      String(post.userId) === selectedUser;

    const matchesSearch =
      post.title.toLowerCase().includes(searchText) ||
      post.body.toLowerCase().includes(searchText);

    const matchesCategory =
      selectedApiCategory === "all" ||
      category === selectedApiCategory;

    const matchesSaved =
      !showSavedApiOnly ||
      savedApiPosts.includes(post.id);

    return matchesUser &&
      matchesSearch &&
      matchesCategory &&
      matchesSaved;

  });

  currentApiPosts = filteredPosts;
  apiCurrentPage = 1;

  if (filteredPosts.length === 0) {

    apiTest.innerHTML = `
      <div class="api-error">
        <strong>⚠️ No posts found!</strong>
        <p>
          No matching news found.
          Save some news or change your filters.
        </p>
      </div>
    `;

    apiPageNumber.textContent = "Page 0";
    apiPrevBtn.disabled = true;
    apiNextBtn.disabled = true;

    return;
  }

  renderApiPagination(filteredPosts);

}


