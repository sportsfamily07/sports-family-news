document.addEventListener("click", function(event) {

  const deleteButton =
    event.target.closest(".delete-comment");

  if (!deleteButton) return;


  const newsId =
    Number(deleteButton.dataset.id);


  const commentIndex =
    Number(deleteButton.dataset.index);


  const commentKey =
    "newsComments_" + newsId;


  let comments =
    JSON.parse(
      localStorage.getItem(commentKey)
    ) || [];


  if (
    commentIndex < 0 ||
    commentIndex >= comments.length
  ) {
    return;
  }


  const confirmDelete =
    confirm("Delete this comment?");


  if (!confirmDelete) {
    return;
  }


  // Delete comment
  comments.splice(
    commentIndex,
    1
  );


  // Save updated comments
  localStorage.setItem(
    commentKey,
    JSON.stringify(comments)
  );


  // Find current card
  const card =
    deleteButton.closest(".news-card");


  if (!card) return;


  // Re-render comment area
  const commentArea =
    card.querySelector(".comment-area");


  if (!commentArea) return;


  const commentList =
    commentArea.querySelector(".comment-list");


  if (!commentList) return;


  commentList.innerHTML = "";


  // Show updated comments
  comments.forEach(function(comment, index) {

    const commentItem =
      document.createElement("div");


    commentItem.className =
      "comment-item";


    commentItem.innerHTML = `

      <p>
        ${comment.text}
      </p>

      <small>
        ${comment.date}
      </small>

      <button
        class="delete-comment"
        data-id="${newsId}"
        data-index="${index}">
        🗑️ Delete
      </button>

    `;


    commentList.appendChild(
      commentItem
    );

  });


  // Update comment count
  const commentButton =
    card.querySelector(
      '.comment-btn[data-id="' +
      newsId +
      '"]'
    );


  if (commentButton) {

    commentButton.textContent =
      "💬 Comment " + comments.length;

  }

});

