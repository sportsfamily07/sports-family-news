document.addEventListener("click", function(event) {

  const submitButton =
    event.target.closest(".submit-comment");

  if (!submitButton) return;


  const newsId =
    Number(submitButton.dataset.id);


  const commentArea =
    submitButton.closest(".comment-area");

  if (!commentArea) return;


  const input =
    commentArea.querySelector(".comment-input");


  const commentText =
    input.value.trim();


  if (commentText === "") {

    alert("Please write your comment.");

    input.focus();

    return;

  }


  const commentKey =
    "newsComments_" + newsId;


  let comments =
    JSON.parse(
      localStorage.getItem(commentKey)
    ) || [];


  comments.push({

    text: commentText,

    date: new Date().toLocaleString()

  });


  localStorage.setItem(
    commentKey,
    JSON.stringify(comments)
  );


  input.value = "";


  // Reload comment area
  const commentList =
    commentArea.querySelector(".comment-list");


  const newComment =
    comments[comments.length - 1];


  const commentItem =
    document.createElement("div");


  commentItem.className =
    "comment-item";


  commentItem.innerHTML = `

    <p>
      ${newComment.text}
    </p>

    <small>
      ${newComment.date}
    </small>

    <button
      class="delete-comment"
      data-id="${newsId}"
      data-index="${comments.length - 1}">
      🗑️ Delete
    </button>

  `;


  commentList.appendChild(
    commentItem
  );


  // Update Comment Count
  const commentButton =
    document.querySelector(
      '.comment-btn[data-id="' +
      newsId +
      '"]'
    );


  if (commentButton) {

    commentButton.textContent =
      "💬 Comment " + comments.length;

  }


  alert(
    "Comment posted successfully! 💬"
  );

});

