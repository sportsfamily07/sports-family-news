// LIKE BUTTON
// =========================

document.addEventListener("click", function(event) {

  const likeButton =
    event.target.closest(".like-btn");

  if (!likeButton) return;

  const newsId =
    Number(likeButton.dataset.id);

  const likeKey =
    "newsLikes_" + newsId;

  const likedKey =
    "newsLiked_" + newsId;

  let likeCount =
    Number(localStorage.getItem(likeKey)) || 0;

  let isLiked =
    localStorage.getItem(likedKey) === "true";

  if (isLiked) {

    likeCount--;

    isLiked = false;

  } else {

    likeCount++;

    isLiked = true;

  }

  localStorage.setItem(
    likeKey,
    likeCount
  );

  localStorage.setItem(
    likedKey,
    isLiked
  );

  const countElement =
    likeButton.querySelector(".like-count");

  if (countElement) {
    countElement.textContent = likeCount;
  }

  likeButton.classList.toggle(
    "liked",
    isLiked
  );

});

