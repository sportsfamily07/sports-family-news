function renderApiPagination(posts) {

  const totalPages =
    Math.ceil(posts.length / apiPostsPerPage);

  // No pages
  if (totalPages === 0) {
    apiPageNumber.textContent = "Page 0";
    apiPrevBtn.disabled = true;
    apiNextBtn.disabled = true;
    return;
  }

  // Keep page within range
  if (apiCurrentPage > totalPages) {
    apiCurrentPage = totalPages;
  }

  const start =
    (apiCurrentPage - 1) * apiPostsPerPage;

  const end =
    start + apiPostsPerPage;

  const pagePosts =
    posts.slice(start, end);

  renderApiPosts(pagePosts);

  // Page number
  apiPageNumber.textContent =
    `Page ${apiCurrentPage} of ${totalPages}`;

  // Previous button
  apiPrevBtn.disabled =
    apiCurrentPage === 1;

  // Next button
  apiNextBtn.disabled =
    apiCurrentPage === totalPages;
}

