// Delete Comment
detailsCommentList.addEventListener(
  "click",
  function(event) {

    const deleteButton =
      event.target.closest(
        ".details-delete-comment"
      );

    if (!deleteButton) {
      return;
    }


    const commentIndex =
      Number(
        deleteButton.dataset.index
      );


    let comments =
      JSON.parse(
        localStorage.getItem(commentKey)
      ) || [];


    if (
      commentIndex < 0 ||
      commentIndex >= comments.length
    ) {
      return;
    }


    const confirmDelete =
      confirm("Delete this comment?");


    if (!confirmDelete) {
      return;
    }


    comments.splice(
      commentIndex,
      1
    );


    localStorage.setItem(
      commentKey,
      JSON.stringify(comments)
    );


    loadDetailsComments();

  }
);


